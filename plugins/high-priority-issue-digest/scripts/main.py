import json
import os
import urllib.parse
import urllib.request

REPOSITORIES = ("OpenHands/OpenHands", "OpenHands/software-agent-sdk")
SLACK_CHANNEL = "C0BGK8NRYUX"
ISSUE_LABEL = "priority:high"
MAX_ISSUES_PER_REPOSITORY = 5


def get_secret(name):
    """Fetch a named secret stored in the agent server."""
    url = os.environ.get("AGENT_SERVER_URL", "").rstrip("/")
    key = os.environ.get("SESSION_API_KEY") or os.environ.get("OH_SESSION_API_KEYS_0", "")
    with urllib.request.urlopen(urllib.request.Request(
        f"{url}/api/settings/secrets/{name}", headers={"X-Session-API-Key": key}
    )) as r:
        return r.read().decode().strip()


def fire_callback(status="COMPLETED", error=None):
    """Signal run completion. MUST be called on every exit path — success AND error."""
    url = os.environ.get("AUTOMATION_CALLBACK_URL", "")
    if not url: return
    body = {"status": status, "run_id": os.environ.get("AUTOMATION_RUN_ID", "")}
    if error: body["error"] = error
    try:
        urllib.request.urlopen(urllib.request.Request(url, data=json.dumps(body).encode(), headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {os.environ.get('AUTOMATION_CALLBACK_API_KEY', '')}",
        }))
    except Exception as e: print(f"Callback error: {e}")


def request_json(url, token, payload=None):
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "User-Agent": "oss-openhands-priority-digest",
    }
    data = None
    if payload is not None:
        data = json.dumps(payload).encode()
        headers["Content-Type"] = "application/json; charset=utf-8"
    request = urllib.request.Request(url, data=data, headers=headers)
    with urllib.request.urlopen(request, timeout=30) as response:
        result = json.load(response)
    if isinstance(result, dict) and result.get("ok") is False:
        raise RuntimeError(result.get("error", "API request failed"))
    return result


def get_high_priority_issues(repository, github_token):
    query = urllib.parse.urlencode({
        "state": "open",
        "labels": ISSUE_LABEL,
        "sort": "updated",
        "direction": "desc",
        "per_page": 100,
    })
    issues = request_json(
        f"https://api.github.com/repos/{repository}/issues?{query}",
        github_token,
    )
    return [issue for issue in issues if "pull_request" not in issue]


def format_summary(issues_by_repository):
    total = sum(len(issues) for issues in issues_by_repository.values())
    lines = [f"*High-priority GitHub issues — {total} open*"]

    for repository, issues in issues_by_repository.items():
        lines.append(f"*{repository}* — {len(issues)}")
        for issue in issues[:MAX_ISSUES_PER_REPOSITORY]:
            title = issue["title"].replace("\n", " ").strip()
            lines.append(f"• <{issue['html_url']}|#{issue['number']}> {title}")
        remaining = len(issues) - MAX_ISSUES_PER_REPOSITORY
        if remaining > 0:
            lines.append(f"• +{remaining} more")

    lines.append("_Generated by OpenHands automation on behalf of the user._")
    return "\n".join(lines)


def main():
    github_token = get_secret("GITHUB_TOKEN")
    slack_token = get_secret("SLACK_BOT_TOKEN")
    issues = {
        repository: get_high_priority_issues(repository, github_token)
        for repository in REPOSITORIES
    }
    request_json(
        "https://slack.com/api/chat.postMessage",
        slack_token,
        {"channel": SLACK_CHANNEL, "text": format_summary(issues)},
    )


if __name__ == "__main__":
    try:
        main()
        fire_callback()
    except Exception as error:
        fire_callback("FAILED", str(error))
        raise
