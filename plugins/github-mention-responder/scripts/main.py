#!/usr/bin/env python3
"""GitHub mention responder — event-triggered.

The GitHub analogue of the Slack channel monitor. Someone on the whitelist
mentions the bot in an issue, a pull request, or a comment on either, and this
starts an agent conversation about that thread.

Continuation is the service's job, not this script's. The trigger sets

    destination:      continue_conversation
    subject_key_expr: join('/', [repository.full_name,
                                 to_string(issue.number || pull_request.number)])

so every later event on the same issue or pull request is delivered as another
turn on the conversation this run created, and this script does not run again.
That is deliberate: the Slack monitor keeps its own thread->conversation map in
the KV store, and that store is a single 64 KB document per automation which
has already overflowed once and silently wedged an automation for four days.
The service needs no map at all: it derives the conversation id from the
subject, and hands it to this script as AUTOMATION_CONVERSATION_ID so the
conversation is created under the id later turns are addressed to.

The consequence shapes everything below: on a follow-up there is no script to
post the reply, so *the agent* must own posting to GitHub, on the first turn as
much as on the tenth. This script's whole job is to hand the agent enough
context and instruction to do that, register the conversation, and get out of
the way. It deliberately does not wait for the answer.

The whitelist is enforced twice. The trigger filter checks `sender.login`, so a
stranger's mention never creates a run at all and costs nothing. The check here
is defence in depth for the case where the trigger is edited carelessly.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request
from urllib.parse import quote

# ── Configuration ─────────────────────────────────────────────────────────────
CONFIG = {
    # Kept in step with the trigger filter. The filter is what actually gates a
    # run; this list only refuses one that slipped through.
    "authorized_logins": [
        "VascoSch92",
        "neubig",
    ],
    "trigger_phrase": "@all-hands-bot",
    "repos": [
        "OpenHands/extensions",
        "OpenHands/OpenHands",
        "OpenHands/software-agent-sdk",
        "OpenHands/typescript-client",
        "OpenHands/automation",
    ],
    # Appended to every comment the agent posts, matching the other automations.
    "disclosure": "_Generated by OpenHands AI on behalf of the user._",
}

AUTHORIZED_LOGINS = frozenset(login.lower() for login in CONFIG["authorized_logins"])
TRIGGER_PHRASE = CONFIG["trigger_phrase"]
ALLOWED_REPOS = frozenset(CONFIG["repos"])
DISCLOSURE = CONFIG["disclosure"]

HTTP_TIMEOUT = 30


def log(msg: str) -> None:
    print(msg, flush=True)


# ── Agent server ──────────────────────────────────────────────────────────────

def _agent_url() -> str:
    return os.environ.get("AGENT_SERVER_URL", "http://127.0.0.1:18000").rstrip("/")


def _api_key() -> str:
    return os.environ.get("SESSION_API_KEY") or os.environ.get("OH_SESSION_API_KEYS_0") or ""


def _oh(method: str, path: str, body: dict | None = None) -> dict:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(
        f"{_agent_url()}{path}", data=data, method=method,
        headers={"X-Session-API-Key": _api_key(), "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as r:
            raw = r.read()
            return json.loads(raw) if raw.strip() else {}
    except urllib.error.HTTPError as exc:
        raise RuntimeError(f"Agent API {method} {path} -> {exc.code}: {exc.read().decode()[:300]}")


def _settings() -> dict:
    req = urllib.request.Request(
        f"{_agent_url()}/api/settings",
        headers={"X-Session-API-Key": _api_key(), "X-Expose-Secrets": "plaintext"},
    )
    with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as r:
        return json.loads(r.read())


def _profile_llm(name: str) -> dict | None:
    """Full LLM config for a named model profile, or None if unusable.

    Needs its own request rather than _oh(): the api_key only comes back with
    X-Expose-Secrets. A miss falls back to the server's active profile rather
    than failing the run.
    """
    req = urllib.request.Request(
        f"{_agent_url()}/api/profiles/{quote(name, safe='')}",
        headers={"X-Session-API-Key": _api_key(), "X-Expose-Secrets": "plaintext"},
    )
    try:
        with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as r:
            return json.loads(r.read()).get("config") or None
    except Exception as exc:
        log(f"warning: model profile {name!r} not usable ({exc}); using active profile")
        return None


# ── Reading the event ─────────────────────────────────────────────────────────

class Mention:
    """The one thing that was said, and where."""

    def __init__(self, payload: dict):
        self.payload = payload
        self.repo = (payload.get("repository") or {}).get("full_name") or ""
        self.sender = ((payload.get("sender") or {}).get("login") or "")
        issue = payload.get("issue") or {}
        pull = payload.get("pull_request") or {}
        comment = payload.get("comment") or {}
        review = payload.get("review") or {}

        self.number = issue.get("number") or pull.get("number")
        self.title = issue.get("title") or pull.get("title") or ""
        # A comment on a PR arrives as an `issue` with a `pull_request` key on
        # it, so the presence of `pull_request` anywhere is the reliable tell.
        self.is_pr = bool(pull) or bool(issue.get("pull_request"))
        self.kind = "pull request" if self.is_pr else "issue"

        # Whichever body carried the mention, most specific first.
        for text, where in (
            (comment.get("body"), "a comment"),
            (review.get("body"), "a review"),
            (issue.get("body"), "the issue description"),
            (pull.get("body"), "the pull request description"),
        ):
            if text and TRIGGER_PHRASE.lower() in text.lower():
                self.text, self.where = text, where
                break
        else:
            self.text, self.where = "", "an unknown place"

        self.url = (
            comment.get("html_url")
            or review.get("html_url")
            or issue.get("html_url")
            or pull.get("html_url")
            or ""
        )

    @property
    def thread_key(self) -> str:
        return f"{self.repo}#{self.number}"

    def problems(self) -> list[str]:
        """Reasons this run should not have happened. Empty means proceed."""
        bad = []
        if self.repo not in ALLOWED_REPOS:
            bad.append(f"repository {self.repo!r} is not in the allowed list")
        if self.sender.lower() not in AUTHORIZED_LOGINS:
            bad.append(f"{self.sender!r} is not on the whitelist")
        if not self.number:
            bad.append("the event names no issue or pull request")
        if not self.text:
            bad.append(f"no {TRIGGER_PHRASE} mention found in the event body")
        return bad


# ── The prompt ────────────────────────────────────────────────────────────────

def build_prompt(m: Mention) -> str:
    """The first turn.

    It has to carry the standing instructions too, because every later event on
    this thread arrives as a bare JSON blob appended by the service, with no
    script to wrap it in guidance.
    """
    return f"""You are answering a mention of {TRIGGER_PHRASE} on GitHub.

## Where you are

- Repository: `{m.repo}`
- {m.kind.capitalize()}: #{m.number} — {m.title}
- Mentioned by: @{m.sender}, in {m.where}
- Link: {m.url}

## What was said

{m.text}

## What to do

For a pull-request review request in OpenHands/OpenHands,
OpenHands/software-agent-sdk, OpenHands/automation, or OpenHands/extensions,
the dedicated PR Reviewer automation owns code reviews. Do not independently
review the diff or post a review-shaped comment. Read the PR's requested
reviewers and submitted reviews first. If all-hands-bot is already requested,
or has submitted a review of the current head, finish without posting anything.
Otherwise request it once with:
`gh pr edit {m.number} --repo {m.repo} --add-reviewer all-hands-bot`
Then finish without a mention comment. This routing rule also applies to later
turns. Other requests (explanations, fixes, questions about review findings) still
follow the normal mention-response flow below.

1. Read the {m.kind} for context first: `gh issue view {m.number} --repo {m.repo} --comments`
   (use `gh pr view` instead when it is a pull request). Read the linked comment
   before answering, so you respond to what was actually asked.
2. Do the work that was asked of you. You have a terminal and a file editor. If
   the request needs the code, clone it into your working directory rather than
   guessing. The `GITHUB_TOKEN` secret is available for `gh` and for git.
3. Reply by posting a comment on that same {m.kind}, with exactly this command:
   `gh issue comment {m.number} --repo {m.repo} --body-file FILE`
   (or `gh pr comment`). Write the body to FILE first so that backticks and
   newlines survive the shell, and write it with the file editor -- the
   terminal rejects a heredoc as "multiple commands at once".
   Never post with `gh api ... -f body=@FILE`. In `gh api`, `-f` sends the
   value as a literal string, so the comment body becomes the text `@FILE`
   instead of your answer. Only `-F` reads a file. That mistake still exits 0
   and still prints a real comment URL, so nothing will tell you it happened.
4. Confirm what you actually posted before you finish:
   `gh issue view {m.number} --repo {m.repo} --comments | tail -30`
   If the body is not the text you wrote, delete that comment and post it
   again with `--body-file`.
5. End every comment you post with this line, exactly:
   {DISCLOSURE}

## Standing instructions for the rest of this conversation

This conversation is bound to `{m.repo}#{m.number}`. When anyone on the
whitelist mentions {TRIGGER_PHRASE} again on that same {m.kind}, the new event
is appended to this conversation as a raw JSON payload rather than as a written
question. When that happens:

- The new request arrives as the message itself: who wrote it, its text, and a
  link to it. (A payload shape the service does not recognise still arrives as
  raw JSON; the request is then in `comment.body`, `review.body`, or the issue
  or pull request body.)
- Treat it as the next message in an ongoing conversation. You already have the
  earlier context, so do not start over and do not re-introduce yourself.
- Answer it the same way: do the work, then post a comment on #{m.number}
  ending with the disclosure line -- with `--body-file`, never
  `gh api -f body=@FILE`, and check the posted body afterwards, exactly as
  above. This applies to every turn, not just the first.
- Ignore any payload whose body does not mention {TRIGGER_PHRASE}, and ignore
  anything posted by `all-hands-bot` itself, which is you. Answering your own
  comment would loop.

Never push commits or open pull requests unless the person explicitly asks you
to. Answering in a comment is the default.
"""


# ── Conversation ──────────────────────────────────────────────────────────────

def create_conversation(initial_message: str, workspace_key: str) -> str:
    """Create the conversation, in its own working directory.

    The directory is per thread. Sharing one across threads lets an agent
    stumble onto an unrelated checkout left by an earlier conversation and
    report confidently on the wrong repository.
    """
    workspace_base = os.environ.get("WORKSPACE_BASE", "")
    root = (
        os.path.dirname(os.path.dirname(os.path.abspath(workspace_base)))
        if workspace_base else os.path.expanduser("~/.openhands/workspaces")
    )
    safe_key = re.sub(r"[^A-Za-z0-9_-]", "_", workspace_key)
    workspace_dir = os.path.join(root, "github-mention-conversations", safe_key)
    os.makedirs(workspace_dir, exist_ok=True)

    settings = _settings()
    agent_settings = settings.get("agent_settings", {})

    # Only the built-in presets read AUTOMATION_MODEL for us; a hand-written
    # script that ignores it silently uses whichever profile is active on the
    # server, which makes the automation's model setting look like a no-op.
    llm = agent_settings.get("llm", {})
    profile = os.environ.get("AUTOMATION_MODEL") or ""
    if profile:
        llm = _profile_llm(profile) or llm
    log(f"llm: {llm.get('model')} (profile: {profile or 'active'})")

    payload: dict = {
        "workspace": {"working_dir": workspace_dir},
        "agent": {
            "kind": "Agent",
            "llm": llm,
            "tools": [{"name": "terminal"}, {"name": "file_editor"}],
        },
        "initial_message": {"content": [{"text": initial_message}]},
    }

    try:
        secrets_list = _oh("GET", "/api/settings/secrets").get("secrets", [])
    except Exception as exc:
        log(f"warning: could not list secrets: {exc}")
        secrets_list = []
    secrets: dict = {}
    for s in secrets_list:
        name = s.get("name", "")
        if not name:
            continue
        lookup: dict = {"kind": "LookupSecret", "url": f"/api/settings/secrets/{name}"}
        if _api_key():
            lookup["headers"] = {"X-Session-API-Key": _api_key()}
        if s.get("description"):
            lookup["description"] = s["description"]
        secrets[name] = lookup
    if secrets:
        payload["secrets"] = secrets

    mcp = agent_settings.get("mcp_config")
    if isinstance(mcp, dict) and mcp.get("mcpServers"):
        payload["mcp_config"] = mcp

    # The service derives this thread's conversation id from its subject and
    # addresses every follow-up turn to that id. Create under it, or the
    # continuation POSTs to a conversation that does not exist, the 404 is
    # swallowed as an ordinary reaped sandbox, and each mention silently opens
    # a fresh, context-blind conversation.
    derived_id = os.environ.get("AUTOMATION_CONVERSATION_ID", "")
    if derived_id:
        payload["conversation_id"] = derived_id
        log(f"creating conversation under derived id {derived_id}")

    return _oh("POST", "/api/conversations", payload)["id"]


# ── Completion callback ───────────────────────────────────────────────────────

def fire_callback(status: str, error: str | None = None, conversation_id: str | None = None) -> None:
    """Report the outcome, and the conversation id with it.

    The binding itself comes from AUTOMATION_CONVERSATION_ID, which is derived
    from the subject before this run starts; reporting the id here records
    what the run actually created, so a mismatch is visible in the run row
    rather than only as a thread that keeps forgetting itself.
    """
    url = os.environ.get("AUTOMATION_CALLBACK_URL", "")
    if not url:
        return
    body: dict = {"status": status, "run_id": os.environ.get("AUTOMATION_RUN_ID", "")}
    if error:
        body["error"] = error[:2000]
    if conversation_id:
        body["conversation_id"] = conversation_id
    req = urllib.request.Request(
        url, data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json",
                 "Authorization": f"Bearer {os.environ.get('AUTOMATION_CALLBACK_API_KEY', '')}"})
    try:
        urllib.request.urlopen(req, timeout=HTTP_TIMEOUT)
    except Exception as exc:
        log(f"callback error (non-fatal): {exc}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> str | None:
    envelope = json.loads(os.environ.get("AUTOMATION_EVENT_PAYLOAD", "{}"))
    event = envelope.get("event") or {}
    payload = event.get("payload") or {}
    if not payload:
        log("no event payload; nothing to do")
        return None

    m = Mention(payload)
    log(f"event {event.get('event_key')!r} on {m.thread_key} from @{m.sender}")

    problems = m.problems()
    if problems:
        # Refusing silently is deliberate. Telling an unauthorized person why
        # they were refused just tells them the bot is there and what to try.
        for p in problems:
            log(f"refusing: {p}")
        return None

    conv_id = create_conversation(build_prompt(m), m.thread_key)
    log(f"conversation {conv_id} started for {m.thread_key}")
    log(f"follow-up mentions on {m.thread_key} will continue this conversation")
    return conv_id


if __name__ == "__main__":
    try:
        cid = main()
        fire_callback("COMPLETED", conversation_id=cid)
    except Exception as exc:
        log(f"failed: {exc}")
        fire_callback("FAILED", str(exc))
        sys.exit(1)
